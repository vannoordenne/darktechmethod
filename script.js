function setLang(lang) {
  const strings = copy[lang];
  if (!strings) return;

  document.documentElement.lang = lang;
  document.title = strings.title;
  document.querySelector('meta[name="description"]').content = strings.description;

  const ogTitle = document.querySelector('meta[property="og:title"]');
  const ogDesc = document.querySelector('meta[property="og:description"]');
  if (ogTitle) ogTitle.content = strings.title;
  if (ogDesc) ogDesc.content = strings.lede;

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n;
    if (strings[key]) el.textContent = strings[key];
  });

  document.querySelectorAll('.lang-btn').forEach((btn) => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  localStorage.setItem('lang', lang);
}

const saved = localStorage.getItem('lang');
const browser = navigator.language?.startsWith('nl') ? 'nl' : 'en';
setLang(saved || browser);

document.querySelectorAll('.lang-btn').forEach((btn) => {
  btn.addEventListener('click', () => setLang(btn.dataset.lang));
});

// Keep methode open on load; others closed
document.querySelectorAll('.term-block').forEach((block, index) => {
  if (index === 0) block.open = true;
  else block.open = false;
});
